function projectReviewSection(): string {
  const start = appSource.indexOf('<section aria-labelledby="project-proposal-heading">');
  const end = appSource.indexOf("</section>", start);
  if (start < 0 || end < 0) throw new Error("M310 project proposal review section is missing.");
  return appSource.slice(start, end);
}

